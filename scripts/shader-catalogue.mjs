// Write skills/shader-video/effects.md, the catalogue of effects in the installed `shaders`
// package: npm run shader-catalogue. Run it again after upgrading the package.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const dist = join("node_modules", "shaders", "dist");
const { version } = JSON.parse(readFileSync(join("node_modules", "shaders", "package.json"), "utf8"));
const { shaderRegistry } = await import(pathToFileURL(join(dist, "registry.js")).href);
const chunks = readdirSync(join(dist, "core"));

// The role ("generator", "filter", ...) is in the built chunk named after the effect.
const roleOf = (name) => {
  const chunk = chunks.find((f) => f.startsWith(`${name}-`) && f.endsWith(".js"));
  const role = chunk && readFileSync(join(dist, "core", chunk), "utf8").match(/role:\s*"([a-z-]+)"/);
  return role ? role[1] : "material";
};

// Effects this studio has rendered in a video and checked frame by frame.
const TESTED = new Set(["Aurora", "ChromaticAberration", "FlowingGradient", "Godrays", "Halftone", "IrisWipe", "MeshGradient", "Pixelate", "Plasma", "Vignette"]);
// Effects that read the cursor, a camera, a page element or a file, or keep state from frame to frame.
const UNSAFE_ROLES = new Set(["simulation", "media"]);
const CHECK = new Set(["Glass", "Surface3D", "Irradiance", "CompressionArtifacts", "KeyFrames"]);

const status = (name, role) =>
  UNSAFE_ROLES.has(role) || name.startsWith("Cursor") ? "no" : CHECK.has(name) ? "check" : TESTED.has(name) ? "tested" : "yes";
const value = (v) => (typeof v === "string" ? v : JSON.stringify(v));
const cell = (s) => String(s ?? "").replace(/\|/g, "/").replace(/\n/g, " ");

const groups = new Map();
for (const entry of shaderRegistry) {
  const role = roleOf(entry.name);
  const props = Object.entries(entry.definition.props ?? {})
    .filter(([, c]) => c && "default" in c && JSON.stringify(c.default).length < 40)
    .filter(([k], i) => i < 6 || k === "speed")
    .map(([k, c]) => `${k}=${value(c.default)}`)
    // A default list of stops overrides colorA and colorB; the column says so.
    .concat(Array.isArray(entry.definition.props?.stops?.default) ? ["stops=a default palette that wins over colorA/colorB (pass null to use them)"] : [])
    .join(", ");
  const row = `| ${entry.name} | ${cell(entry.description)} | ${cell(props)} | ${status(entry.name, role)} |`;
  groups.set(role, [...(groups.get(role) ?? []), row]);
}

const ORDER = ["generator", "shape", "material", "filter", "warp", "overlay", "structural", "media", "simulation"];
let out = `# Effects catalogue

Generated by \`npm run shader-catalogue\` from \`shaders@${version}\` (MIT, Copyright (c) 2026 Shader Effects Inc., https://github.com/shader-effects-inc/shaders). Every prop with its range and description: https://shaders.com/docs/components, or the effect's \`index.d.ts\` under \`node_modules/shaders/dist/core/shaders/<Effect>/\`.

Import an effect as \`import { componentDefinition as <Effect> } from "shaders/core/<Effect>"\`.

- **Role**: a generator or shape draws by itself. A material, filter or warp changes the layers you nest in its \`children\`.
- **Frame-safe**: \`tested\` was rendered and checked in this studio. \`yes\` is a pure function of time and props by its role, untested. \`check\` keeps some state or reads the pointer: render two stills of the same frame and compare before using it. \`no\` simulates from the previous frame, or reads the cursor, a camera, a page element or a file: leave it out.
`;
for (const role of ORDER) {
  const rows = groups.get(role);
  if (!rows) continue;
  out += `\n## ${role} (${rows.length})\n\n| Effect | What it draws | Props (default) | Frame-safe |\n|---|---|---|---|\n${rows.join("\n")}\n`;
}
writeFileSync(join("skills", "shader-video", "effects.md"), out);
console.log(`Wrote skills/shader-video/effects.md: ${shaderRegistry.length} effects from shaders@${version}`);
